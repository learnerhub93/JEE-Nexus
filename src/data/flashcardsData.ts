/**
 * Helper to get flashcards for a specific chapter.
 * Converts existing chapter flashcards and combines with curated cards.
 */
export function getChapterRecallCards(chapter: Chapter): ActiveRecallCard[] {
  // 1. Curated cards tagged with this chapterId
  const matchingCurated = HIGH_YIELD_ACTIVE_RECALL_CARDS.filter(
    (card) => card.chapterId === chapter.id
  );

  // 2. Convert chapter's own flashcards if not already in curated
  const convertedChapterCards: ActiveRecallCard[] = (chapter.flashcards || []).map((fc, idx) => {
    return {
      id: `${chapter.id}-fc-${idx}`,
      subject: chapter.subject,
      classLevel: chapter.classLevel,
      chapterId: chapter.id,
      chapterTitle: chapter.title,
      category: (fc.category as FlashcardCategory) || (chapter.subject === 'physics' ? 'physics_formula' : chapter.subject === 'chemistry' ? 'inorganic_exception' : 'maths_identity'),
      categoryLabel: fc.tag || `${chapter.subject.toUpperCase()} Core Concept`,
      prompt: fc.question,
      promptContext: fc.ncertReference || `Ch ${chapter.chapterNumber} NCERT Concept`,
      answer: fc.answer,
      latex: fc.latex,
      mnemonic: fc.mnemonic || `💡 Active Recall Trick: Focus on key terms & dimensional check for ${fc.tag || 'this concept'}!`,
      explanation: fc.explanation,
      tags: [chapter.subject, `Class ${chapter.classLevel}`, fc.tag || 'NCERT Core'],
      highYieldBadge: '🔥 High-Yield',
    };
  });

  // Combine curated first, then chapter cards (avoiding duplicate prompt text)
  const combined: ActiveRecallCard[] = [...matchingCurated];
  for (const c of convertedChapterCards) {
    if (!combined.some((item) => item.prompt.toLowerCase() === c.prompt.toLowerCase())) {
      combined.push(c);
    }
  }

  return combined;
}
